import type { ComplaintMessage, Merchant } from "@/db/schema";
import type { LedgerVerification } from "@/lib/ledger/verify";
import type { CustomerHistory } from "@/lib/orders/history";
import type { OrderRecord } from "@/lib/orders/queries";
import { formatDateTime } from "@/lib/utils";
import { PdfBuilder } from "./kit";
import {
  communicationSection,
  deliverySection,
  disputeSection,
  hasSimulatedData,
  integritySection,
  orderSummarySection,
  packingSection,
  paymentSection,
  timelineSection,
} from "./sections";

/**
 * The full evidence record for one order as a PDF: order, payment, packing,
 * delivery, communication, chargeback, timeline and integrity appendix.
 */
export async function buildOrderReport(input: {
  merchant: Merchant;
  record: OrderRecord;
  history: CustomerHistory;
  messages: ComplaintMessage[];
  verification: LedgerVerification | null;
  generatedBy: string;
}): Promise<Uint8Array> {
  const { merchant, record, history, messages, verification, generatedBy } = input;
  const generatedAt = new Date();

  const pdf = await PdfBuilder.create({
    title: `Order evidence report ${record.order.number}`,
    subject: `Evidence record for ${merchant.name} order ${record.order.number}`,
    footer: `${merchant.name} order ${record.order.number} | Generated by Verity ${formatDateTime(generatedAt)}`,
    baseSize: 10.5,
  });

  pdf.title(
    `Order evidence report: ${record.order.number}`,
    `${merchant.name}. Generated ${formatDateTime(generatedAt, true)} by ${generatedBy}.`,
  );
  if (hasSimulatedData(record)) {
    pdf.note(
      "Entries marked [simulated] were produced by a demo simulator or seed data, not by a live external system.",
    );
  }

  orderSummarySection(pdf, record, history);
  paymentSection(pdf, record);
  await packingSection(pdf, record);
  await deliverySection(pdf, record);
  communicationSection(pdf, record, messages);
  disputeSection(pdf, record);
  timelineSection(pdf, record.events);
  integritySection(pdf, record, verification);

  return pdf.finish();
}
